import re


class CitationValidator:
    """
    Validates citations generated by the RAG LLM.

    Expected citation format:
        [1]
        [2]
        [3]

    The validator checks:
    1. Every citation number exists.
    2. There are no invented citation numbers.
    3. The answer contains at least one citation for factual content.
    """

    CITATION_PATTERN = re.compile(r"\[(\d+)\]")

    def validate(
        self,
        answer: str,
        number_of_sources: int,
    ) -> dict:
        if not answer or not answer.strip():
            return {
                "valid": False,
                "answer": answer,
                "citations": [],
                "invalid_citations": [],
                "message": "Answer is empty.",
            }

        citation_numbers = [
            int(number)
            for number in self.CITATION_PATTERN.findall(answer)
        ]

        # Remove duplicates while preserving order
        citations = list(dict.fromkeys(citation_numbers))

        invalid_citations = [
            number
            for number in citations
            if number < 1 or number > number_of_sources
        ]

        if invalid_citations:
            return {
                "valid": False,
                "answer": answer,
                "citations": citations,
                "invalid_citations": invalid_citations,
                "message": (
                    "Answer contains citation numbers that do not "
                    "correspond to retrieved sources."
                ),
            }

        return {
            "valid": True,
            "answer": answer,
            "citations": citations,
            "invalid_citations": [],
            "message": "All citations are valid.",
        }